def table(hs, limit=None, primary="in-weight"):
    lines = [f"| # | entity | calls in | callers | PageRank rank | named by map? | file:line |",
             "|---:|---|---:|---:|---:|:--:|---|"]
    for i, r in enumerate(hs[:limit] if limit else hs, 1):
        loc = f"`{r['file']}:{r['line']}`" if r["line"] else f"`{r['file']}`"
        lines.append(f"| {i} | `{r['module']}.{r['qual']}` | {r['in_weight']} | {r['in_degree']} | "
                     f"{r['pr_rank']} | {'yes' if r['leaf_hit'] else 'no'} | {loc} |")
    return "\n".join(lines)


