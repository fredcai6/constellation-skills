# ---------------- the artifact: ranked hole list ----------------
# Primary ordering uses in-weight (total internal call count), the only signal that
# beat the random baseline against the curated map (p=0.0005 at K=30). PageRank is
# carried as a column, not as the ordering, because it did not validate.
for i, r in enumerate(sorted(rows, key=lambda r: (-r["in_weight"], -r["in_degree"])), 1):
    r["iw_rank"] = i
