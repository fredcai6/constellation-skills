def is_private(r):
    return any(p.startswith("_") and not p.startswith("__") for p in r["qual"].split("."))


def report(name, pool, key):
    ranked = sorted(pool, key=key)
    n = len(pool)
    base = sum(r["leaf_hit"] for r in pool) / n if n else 0
    out = [f"\n=== {name} ===  population={n}  base={base:.1%}"]
    for K in (10, 20, 30):
        top = ranked[:K]
        h = sum(r["leaf_hit"] for r in top)
        lift = (h / K / base) if base else float("nan")
        out.append(f"{K:>5} {h:>3} hits {h/K:>7.1%}  lift={lift:>5.2f}x")
    print("\n".join(out))
    return ranked, base


