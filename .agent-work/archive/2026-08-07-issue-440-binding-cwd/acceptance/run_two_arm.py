def log(msg: str) -> None:
    print("[{0}] {1}".format(datetime.now().strftime("%H:%M:%S"), msg), flush=True)


def run(cmd, cwd=None, env=None, timeout=None, capture=True):
    return subprocess.run(
        cmd, cwd=str(cwd) if cwd else None, env=env, timeout=timeout,
        capture_output=capture, text=True, encoding="utf-8", errors="replace",
    )


def _force_rm(path: Path) -> None:
    """rmtree that survives git's read-only pack files on Windows."""
    def onerror(func, p, exc):
        try:
            os.chmod(p, 0o700)
            func(p)
        except Exception:
            pass
    if path.exists():
        shutil.rmtree(path, onexc=onerror)
    if path.exists():                       # last resort
        run(["cmd", "/c", "rmdir", "/s", "/q", str(path)])


def sha256(path: Path) -> str | None:
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError:
        return None


