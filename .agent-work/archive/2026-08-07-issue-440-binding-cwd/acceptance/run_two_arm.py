# --------------------------------------------------------------------------- #
# launching an arm
# --------------------------------------------------------------------------- #

def launch(prompt: str, cwd: Path, settings: Path, model: str, log_path: Path,
           timeout: int) -> dict:
    """A headless `claude -p` with cwd AND CLAUDE_PROJECT_DIR on the sandbox main.

    That pairing is the defect's own precondition: the session's project dir is
    the main checkout while the work happens in the worktree. The ABSOLUTE hook
    path in `settings` is what makes the arm's code run anyway.
    """
    env = dict(os.environ)
    env["CLAUDE_PROJECT_DIR"] = str(cwd)
    env["BASH_MAX_OUTPUT_LENGTH"] = str(FILLER_CHARS + 50_000)
    cmd = [str(CLAUDE), "-p", prompt,
           "--settings", str(settings),
           "--model", model,
           "--permission-mode", "acceptEdits",
           "--add-dir", str(cwd.parent)]
    started = time.time()
    timed_out = False
    try:
        r = run(cmd, cwd=cwd, env=env, timeout=timeout)
        out, err, rc = r.stdout, r.stderr, r.returncode
    except subprocess.TimeoutExpired as exc:
        timed_out = True
        out = (exc.stdout or b"").decode("utf-8", "replace") if isinstance(exc.stdout, bytes) else (exc.stdout or "")
        err = (exc.stderr or b"").decode("utf-8", "replace") if isinstance(exc.stderr, bytes) else (exc.stderr or "")
        rc = None
    elapsed = time.time() - started
    log_path.write_text(
        "CMD: {0}\nCWD: {1}\nCLAUDE_PROJECT_DIR: {1}\nEXIT: {2}\nTIMED_OUT: {3}\n"
        "ELAPSED_S: {4:.1f}\n\n--- STDOUT ---\n{5}\n--- STDERR ---\n{6}\n".format(
            " ".join(cmd[:1] + ["-p", "<prompt>"] + cmd[3:]), cwd, rc, timed_out,
            elapsed, out, err),
        encoding="utf-8")
    return {"exit": rc, "timed_out": timed_out, "elapsed_s": round(elapsed, 1),
            "stdout": out, "stderr": err}


# --------------------------------------------------------------------------- #
# preflight -- the arm trees are COMPLETE and each resolves the way it should
# --------------------------------------------------------------------------- #

def preflight(arms: dict) -> dict:
    """Drive each arm's spine_rail.py directly, once, on a synthetic payload.

    CONFIRMATORY ONLY -- it is not the acceptance and proves nothing about a
    live trip. What it buys is worth having before an hour of headless time:

    1. The arm tree is COMPLETE. An incomplete sibling set makes the gauge
       writer fail its `spine_rail.py` import and write NOTHING, SILENTLY --
       indistinguishable from the bug reproducing.
    2. Each arm resolves the way the fix says it does, and names WHICH RUNG did
       it. The treatment arm must report `path_source: git_worktree` -- derived
       by shelling out to `git worktree list`, not read from anything the
       harness handed it.
    """
    out = {}
    for arm in ("treatment", "control"):
        sb = build_sandbox("pf-" + arm, 1)
        shim = (sb["wt"] / "bin" / "checklist_engine.py").as_posix()
        cmd = ('python "{0}" --file .agent-work/{1}/spine.json claim '
               '--session-id {2} --claimed-by sandbox').format(shim, WORK_ID, ENGINE_SESSION)
        drive = subprocess.run(cmd, shell=True, cwd=str(sb["main"]),
                               capture_output=True, text=True)
        payload = {"session_id": "PFSESSION", "agent_id": "pfagent0001",
                   "cwd": str(sb["main"]), "transcript_path": "absent",
                   "tool_name": "Bash", "tool_input": {"command": cmd}}
        env = dict(os.environ)
        env["CLAUDE_PROJECT_DIR"] = str(sb["main"])
        hook = str(arms[arm] / "scripts" / "hooks" / "spine_rail.py")
        h = subprocess.run(["python", hook, "PostToolUse"], input=json.dumps(payload),
                           text=True, capture_output=True, env=env)
        store = read_json(sb["main"] / ".agent-work" / ".spine-rail-binding.json")
        entry = None
        for val in (store or {}).values():
            for spine_path, e in (val or {}).items():
                entry = {"spine": spine_path, "path_source": (e or {}).get("path_source")}
        out[arm] = {
            "observed_command": cmd,
            "engine_drove_ok": drive.returncode == 0,
            "hook_exit": h.returncode,
            "hook_stderr": (h.stderr or "")[:400],
            "binding_store": store,
            "resolved": entry,
            "spine_really_at": str(sb["spine"]),
            "spine_present_in_sandbox_main": (
                sb["main"] / ".agent-work" / WORK_ID / "spine.json").exists(),
        }
        _force_rm(sb["root"])
    (EVIDENCE / "preflight-arms.json").write_text(json.dumps(out, indent=2),
                                                  encoding="utf-8")
    return out


# --------------------------------------------------------------------------- #
# probe -- is a whole filler file delivered, or middle-truncated?
# --------------------------------------------------------------------------- #

def probe(settings: Path) -> int:
    """Confirm a whole filler file survives ONE Read call.

    A truncated tool result would silently shrink the inflation and could leave
    the subagent under the HARD cap -- a false negative wearing the bug's face.
    Returns the filler count to use; a TRUNCATED verdict is reported, not
    silently worked around.
    """
    root = TMP / "probe"
    _force_rm(root)
    root.mkdir(parents=True)
    make_filler(root / "filler", 1)
    prompt = ("Run this exact Bash command as one tool call:\n"
              'cat "{0}/filler/f01.txt"\n'
              "Then look at the tool result YOU received. If it contains any "
              "truncation marker or notice saying content was omitted or "
              "truncated, reply with exactly TRUNCATED. Otherwise reply with "
              "exactly FULL. Reply with that one word only.").format(
                  (root / "filler").parent.as_posix())
    res = launch(prompt, root, settings, PARENT_MODEL,
                 TMP / "logs" / "probe.log", PROBE_TIMEOUT_S)
    verdict = "TRUNCATED" if "TRUNCATED" in (res["stdout"] or "").upper() else (
        "FULL" if "FULL" in (res["stdout"] or "").upper() else "UNKNOWN")
    log("probe verdict: {0} (exit {1})".format(verdict, res["exit"]))
    (EVIDENCE / "probe.json").write_text(json.dumps({
        "filler_chars": FILLER_CHARS, "verdict": verdict,
        "exit": res["exit"], "stdout": (res["stdout"] or "")[:2000],
    }, indent=2), encoding="utf-8")
    _force_rm(root)
    # FULL: 6 x 200_000 chars ~ 400K tokens. Otherwise assume ~30_000 chars per
    # call survives and take 30 calls to reach a comparable budget.
    return FILLER_COUNT


