def read_json(path: Path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return None


def transcript_diagnostics(sb: dict) -> dict:
    """Where the harness's own session transcript landed, and whether the
    dispatched agent's derived transcript is on disk beside it.

    This is the diagnostic for `docs/GAUGE_WRITER_HOOK.md` "Skip-on-uncertainty,
    enumerated": a missing `subagents/agent-<id>.jsonl` is the
    `subagent-transcript-missing` cause, and a missing session transcript
    entirely is the silent `transcript_path` cause. Without this, a quiet writer
    cannot be told apart from the bug.
    """
    try:
        projects = Path.home() / ".claude" / "projects"
        slug_key = str(sb["main"]).replace(":", "").replace("\\", "-").replace("/", "-")
        cands = [d for d in projects.iterdir()
                 if d.is_dir() and slug_key.lower().lstrip("-") in d.name.lower().lstrip("-")]
        out = []
        for d in cands:
            for jsonl in sorted(d.glob("*.jsonl"), key=lambda p: p.stat().st_mtime,
                                reverse=True)[:3]:
                subs = jsonl.with_suffix("") / "subagents"
                out.append({
                    "session_transcript": str(jsonl),
                    "size": jsonl.stat().st_size,
                    "subagents_dir": str(subs),
                    "subagents_dir_exists": subs.is_dir(),
                    "subagent_transcripts": sorted(p.name for p in subs.glob("*.jsonl"))
                    if subs.is_dir() else [],
                })
        return {"projects_root": str(projects), "slug_key": slug_key,
                "matched_dirs": [str(d) for d in cands], "sessions": out}
    except Exception as exc:
        return {"error": repr(exc)}


def collect(arm: str, sb: dict, res: dict, hook_path: str) -> dict:
    """Everything the verdict rests on, from disk, after the arm has run."""
    store_path = sb["main"] / ".agent-work" / ".spine-rail-binding.json"
    store = read_json(store_path)
    advance_out = sb["spine"].parent / "advance-out.txt"
    adv_text = ""
    adv_exit = None
    if advance_out.exists():
        adv_text = advance_out.read_text(encoding="utf-8", errors="replace")
        for line in adv_text.splitlines():
            if line.startswith("EXIT="):
                try:
                    adv_exit = int(line.split("=", 1)[1].strip())
                except ValueError:
                    pass

    # Attribution: composite key shape, identity_resolution_ms, model.
    composite_keys = []
    entries = []
    if isinstance(store, dict):
        for key, val in store.items():
            if "#" in key:
                composite_keys.append(key)
            if isinstance(val, dict):
                for spine_path, entry in val.items():
                    entries.append({"key": key, "spine": spine_path,
                                    "path_source": (entry or {}).get("path_source"),
                                    "worktree": (entry or {}).get("worktree")})

    gauge_wt = read_json(sb["gauge_wt"])
    gauge_main = read_json(sb["gauge_main"])
    reading = gauge_wt if gauge_wt else gauge_main

    spine_state = read_json(sb["spine"]) or {}
    m1_status = ((spine_state.get("tasks") or {}).get("m1") or {}).get("status")

    return {
        "arm": arm,
        "collected_at": datetime.now(timezone.utc).isoformat(),
        "hook_path": hook_path,
        "parent_model": PARENT_MODEL,
        "subagent_model_requested": SUBAGENT_MODEL,
        "sandbox": {"main": str(sb["main"]), "wt": str(sb["wt"]),
                    "spine": str(sb["spine"])},
        "headless": {"exit": res["exit"], "timed_out": res["timed_out"],
                     "elapsed_s": res["elapsed_s"],
                     "stdout_tail": (res["stdout"] or "")[-1500:]},
        "binding_store_path": str(store_path),
        "binding_store": store,
        "binding_entries": entries,
        "composite_keys": composite_keys,
        "gauge_in_worktree": {"path": str(sb["gauge_wt"]),
                              "exists": sb["gauge_wt"].exists(),
                              "record": gauge_wt},
        "gauge_in_main_phantom": {"path": str(sb["gauge_main"]),
                                  "exists": sb["gauge_main"].exists(),
                                  "record": gauge_main},
        "skip_sidecar_wt": read_json(sb["gauge_wt"].with_name("gauge-skip.json")),
        "skip_sidecar_main": read_json(sb["gauge_main"].with_name("gauge-skip.json")),
        "uncalibrated_wt": read_json(sb["gauge_wt"].with_name("gauge-uncalibrated.json")),
        "transcript_diagnostics": transcript_diagnostics(sb),
        "advance_output": adv_text,
        "advance_exit": adv_exit,
        "m1_status_after": m1_status,
        "attribution": {
            "composite_key_present": bool(composite_keys),
            "identity_resolution_ms": (reading or {}).get("identity_resolution_ms"),
            "gauge_model": (reading or {}).get("model"),
            "subagent_model_id_expected": SUBAGENT_MODEL_ID,
            "fill_fraction": (reading or {}).get("fill_fraction"),
            "observed_at": (reading or {}).get("observed_at"),
            "wall_clock_at_collect": datetime.now(timezone.utc).isoformat(),
        },
    }


