def real_store_fingerprint() -> dict:
    """The LIVE main checkout's binding store, hashed before and after. A live
    Admiral session is using it; the harness must never write it."""
    p = Path("C:/Programs/constellation-skills/.agent-work/.spine-rail-binding.json")
    return {"path": str(p), "sha256": sha256(p),
            "size": p.stat().st_size if p.exists() else None}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--keep", action="store_true", help="leave the temp tree in place")
    ap.add_argument("--probe-only", action="store_true")
    ap.add_argument("--preflight-only", action="store_true")
    ap.add_argument("--arm", choices=["treatment", "control"],
                    help="run only this arm")
    ap.add_argument("--filler-count", type=int, default=None)
    args = ap.parse_args()

    EVIDENCE.mkdir(parents=True, exist_ok=True)
    (TMP / "logs").mkdir(parents=True, exist_ok=True)

    before = real_store_fingerprint()

    log("building arm trees")
    arms = build_arms()
    diff_text = arm_diff(arms)
    (EVIDENCE / "arm-diff.txt").write_text(
        "# recursive diff: control (cbd9aee) vs treatment (HEAD), full scripts/ trees\n"
        "# command: diff -rq <control>/scripts <treatment>/scripts\n\n"
        + (diff_text or "(no differences)\n"), encoding="utf-8")
    log("arm diff:\n" + diff_text)

    settings = build_settings(arms)
    for name, path in settings.items():
        shutil.copy2(path, EVIDENCE / "settings-{0}.json".format(name))

    log("preflight: arm trees complete, resolution rung per arm")
    pf = preflight(arms)
    for arm, d in pf.items():
        log("  {0}: hook_exit={1} resolved={2}".format(arm, d["hook_exit"], d["resolved"]))
    if args.preflight_only:
        return 0

    if args.filler_count is not None:
        filler_count = args.filler_count
    else:
        log("probing tool-output truncation")
        filler_count = probe(settings["treatment"])
    log("filler count = {0} x {1} chars".format(filler_count, FILLER_CHARS))
    if args.probe_only:
        return 0

    which = [args.arm] if args.arm else ["treatment", "control"]
    for arm in which:
        log("=== ARM {0}: building sandbox ===".format(arm))
        sb = build_sandbox(arm, filler_count)
        prompt = parent_prompt(sb, filler_count)
        (EVIDENCE / "prompt-{0}.txt".format(arm)).write_text(prompt, encoding="utf-8")
        hook_path = (arms[arm] / "scripts" / "hooks" / "spine_rail.py").as_posix()
        log("=== ARM {0}: launching headless run (hooks -> {1}) ===".format(arm, hook_path))
        res = launch(prompt, sb["main"], settings[arm], PARENT_MODEL,
                     TMP / "logs" / "{0}.log".format(arm), ARM_TIMEOUT_S)
        log("=== ARM {0}: exit={1} timed_out={2} elapsed={3}s ===".format(
            arm, res["exit"], res["timed_out"], res["elapsed_s"]))
        ev = collect(arm, sb, res, hook_path)
        (EVIDENCE / "arm-{0}.json".format(arm)).write_text(
            json.dumps(ev, indent=2), encoding="utf-8")
        shutil.copy2(TMP / "logs" / "{0}.log".format(arm),
                     EVIDENCE / "headless-{0}.log".format(arm))
        log("collected: gauge_wt={0} gauge_main={1} advance_exit={2}".format(
            ev["gauge_in_worktree"]["exists"], ev["gauge_in_main_phantom"]["exists"],
            ev["advance_exit"]))

    after = real_store_fingerprint()
    (EVIDENCE / "live-checkout-untouched.json").write_text(json.dumps({
        "before": before, "after": after,
        "unchanged": before["sha256"] == after["sha256"] and before["size"] == after["size"],
    }, indent=2), encoding="utf-8")

    if not args.keep:
        log("cleaning up {0}".format(TMP))
        _force_rm(TMP)
    return 0


if __name__ == "__main__":
    sys.exit(main())
