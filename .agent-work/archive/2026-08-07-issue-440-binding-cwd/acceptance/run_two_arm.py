#!/usr/bin/env python
"""Two-arm live-fire acceptance harness for issue #440.

Answers ONE question with evidence:

    Does a HARD governor trip fire from a per-agent gauge reading produced by
    an agent that was dispatched into a worktree?

Not "does the path resolve" -- a fired trip, observed, on a live headless run,
with a byte-identical control arm.

WHY A SANDBOX PAIR AND NOT AN IN-PLACE TEST
-------------------------------------------
Hook code is not fenced by worktree isolation. `CLAUDE_PROJECT_DIR` resolves
once at session launch (#269) and is inherited unchanged by every subagent, so
an agent dispatched into a worktree still executes the MAIN CHECKOUT's hook code
against the MAIN CHECKOUT's state. The mechanism under repair is therefore the
mechanism that would make an in-worktree validation lie.

So each arm is a DISPOSABLE SANDBOX PAIR under a temp directory:

  * sandbox main  -- a scratch `git init` repo standing in for a main checkout.
  * sandbox wt    -- a real `git worktree add` of that repo.

and the arm's hooks are wired BY ABSOLUTE PATH into an arm-private `scripts/`
tree. The headless session is launched with cwd AND `CLAUDE_PROJECT_DIR` set to
the sandbox main -- which is the defect's own precondition -- while the spine it
drives lives in the sandbox worktree.

THE ONLY DIFFERENCE BETWEEN THE TWO ARMS IS WHICH ARM DIRECTORY THE ABSOLUTE
HOOK PATH POINTS AT. Sandbox, prompt, models, spine, filler and command sequence
are generated by the same code for both.

NOTHING IS HAND-INJECTED. The harness never places the sandbox worktree root
into a hook payload field, a fixture, or an environment variable that the hook
reads back. The spine is created in the worktree; the hook must find it.

Usage:
    python run_two_arm.py              # probe, build, run both arms, collect, clean
    python run_two_arm.py --keep       # same but leave the temp tree in place
    python run_two_arm.py --probe-only
    python run_two_arm.py --arm treatment
"""

