# A launcher that puts the ENGINE PROCESS's working directory in the worktree,
# which is what a shell already resident in a worktree gives for free. It exists
# because a headless subagent's Bash tool resets its cwd between calls, so the
# only other way to make a relative `--file` resolve would be a `cd` in the
# observed command -- and the hook PARSES a `cd` target as a candidate root.
#
# THIS IS THE POINT: with no `cd`, the harness places the worktree root in NO
# field the hook reads (not `--file`, not `--worktree`, not a `cd` target, not
# the payload `cwd`, not an environment variable). The hook must DERIVE the
# worktree by shelling out to `git worktree list` -- rung 4, `path_source:
# git_worktree` -- or bind nothing. The shim's own path appears in the command
# text only as the script token, which the resolution never treats as a root.
#
# It derives its own root from __file__ and forwards argv unchanged, so it adds
# no argument the hook could read and preserves the engine's real exit code.
SHIM = '''import os, subprocess, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.exit(subprocess.run(
    [sys.executable, os.path.join(root, "scripts", "checklist_engine.py")] + sys.argv[1:],
    cwd=root).returncode)
'''


def make_filler(dest: Path, count: int) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    rnd = random.Random(4400)
    alphabet = ("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"
                "+/=!@#$%^&*()[]{}<>?;:,.~|")
    for i in range(1, count + 1):
        # Line-shaped so the Read tool's 2000-char per-line truncation never
        # applies, and sized under the ~30_000-char tool-output cap so the whole
        # file arrives with no truncation notice.
        lines = []
        while sum(len(x) + 1 for x in lines) < FILLER_CHARS:
            lines.append("".join(rnd.choice(alphabet) for _ in range(FILLER_LINE_CHARS)))
        (dest / "f{0:02d}.txt".format(i)).write_text("\n".join(lines), encoding="utf-8")


def build_sandbox(arm: str, filler_count: int) -> dict:
    """A scratch `git init` main plus a REAL `git worktree add` of it.

    The spine is created ONLY in the worktree and is never committed, so the
    same relative path does not exist in the sandbox main. The hook is told
    nothing about where it is.
    """
    root = TMP / "run-{0}".format(arm)
    _force_rm(root)
    main = root / "main"
    wt = root / "wt"
    main.mkdir(parents=True)

    # The engine and its ONE sibling import. No hooks live in the sandbox at
    # all, so there is no chance the sandbox's own copy is the code under test.
    (main / "scripts").mkdir()
    for f in ("checklist_engine.py", "gauge_reader.py"):
        shutil.copy2(REPO / "scripts" / f, main / "scripts" / f)
    # No engine-config.json is shipped: this repo has none either, so
    # `load_config` resolves to {} and the engine runs on its defaults --
    # exactly as it does on every real run here.

    for cmd in (["git", "init", "-q", "-b", "main"],
                ["git", "config", "user.email", "sandbox@example.invalid"],
                ["git", "config", "user.name", "sandbox"],
                ["git", "add", "-A"],
                ["git", "commit", "-q", "-m", "sandbox base"]):
        r = run(cmd, cwd=main)
        if r.returncode != 0:
            raise SystemExit("sandbox git failed: {0}\n{1}".format(cmd, r.stderr))
    r = run(["git", "worktree", "add", "-q", "-b", "sbwt", str(wt)], cwd=main)
    if r.returncode != 0:
        raise SystemExit("git worktree add failed: " + (r.stderr or ""))

    # The shim lives in the WORKTREE (untracked), named so the hook's
    # `checklist_engine.py` token test still fires on the observed command.
    (wt / "bin").mkdir(parents=True, exist_ok=True)
    (wt / "bin" / "checklist_engine.py").write_text(SHIM, encoding="utf-8")

    spine_dir = wt / ".agent-work" / WORK_ID
    spine_dir.mkdir(parents=True)
    (spine_dir / "spine.json").write_text(json.dumps(SPINE, indent=2) + "\n",
                                          encoding="utf-8")
    make_filler(wt / "filler", filler_count)
    return {"root": root, "main": main, "wt": wt,
            "spine": spine_dir / "spine.json", "gauge_wt": spine_dir / "gauge.json",
            "gauge_main": main / ".agent-work" / WORK_ID / "gauge.json"}


