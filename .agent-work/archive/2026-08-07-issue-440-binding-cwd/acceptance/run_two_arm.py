# Inflation goes through the READ tool, one file per call.
#
# MEASURED on this box, not assumed (evidence/probe.json, evidence/probe-*.json):
# a tool result is truncated at ~30_000 characters whatever the tool. Bash is
# middle-truncated there and `BASH_MAX_OUTPUT_LENGTH` did NOT lift it on 2.1.223;
# Read has a separate 256KB file ceiling but still delivers only the first
# ~30_000 characters (a 400-line x 600-char file arrived as lines L00001-L00050
# with a truncation notice). So each filler file sits just UNDER that cap and
# arrives whole, and the token budget is made up of call COUNT rather than
# file size.
#
# Filler is high-entropy printable ASCII with no word structure, so byte-pair
# merges mostly fail and the text costs roughly 1.5-2.5 characters per token --
# the opposite of prose. Even at a pessimistic 4 chars/token the budget below
# clears HARD.
#
# claude-sonnet-5's HARD cap is 150_000 ABSOLUTE tokens against a 1_000_000
# window (read from scripts/gauge_reader.py _PROFILES, not assumed):
#
#   24 calls x 28_000 chars = 672_000 chars
#     pessimistic 4.0 chars/token -> ~168_000 tokens  (over HARD)
#     likely      2.5 chars/token -> ~269_000 tokens
#     dense       1.5 chars/token -> ~448_000 tokens  (still < window)
#
# Every case lands over HARD and none approaches the 1M window, so
# auto-compaction cannot reset the reading mid-protocol.
FILLER_CHARS = 28_000
FILLER_COUNT = 24
FILLER_LINE_CHARS = 200

# Per-arm wall-clock bound. A headless run that has not finished by then is
# killed and reported as such rather than hanging the gate.
