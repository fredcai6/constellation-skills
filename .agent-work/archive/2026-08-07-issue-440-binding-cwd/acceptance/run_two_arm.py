def build_arms() -> dict:
    """Two complete `scripts/` trees. Treatment = this worktree's current
    scripts/; control = `git archive <BASE_COMMIT>`.

    COMPLETE, not two files: gauge_writer_hook.py imports spine_rail.py as a
    FILESYSTEM SIBLING and, if the sibling set is incomplete, writes NOTHING,
    SILENTLY -- which would look exactly like the bug reproducing.
    """
    arms = TMP / "arms"
    _force_rm(arms)
    treatment = arms / "treatment"
    control = arms / "control"
    treatment.mkdir(parents=True)
    control.mkdir(parents=True)

    shutil.copytree(REPO / "scripts", treatment / "scripts",
                    ignore=shutil.ignore_patterns("__pycache__"))

    tar = control / "control.tar"
    with open(tar, "wb") as fh:
        proc = subprocess.run(["git", "archive", BASE_COMMIT, "scripts"],
                              cwd=str(REPO), stdout=fh)
    if proc.returncode != 0:
        raise SystemExit("git archive {0} failed".format(BASE_COMMIT))
    r = run(["tar", "-xf", str(tar)], cwd=control)
    if r.returncode != 0:
        raise SystemExit("tar extract failed: " + (r.stderr or ""))
    tar.unlink()

    return {"treatment": treatment, "control": control}


def arm_diff(arms: dict) -> str:
    """Recursive diff of the two arm trees. Load-bearing evidence: it is what
    proves the arms differ ONLY in scripts/hooks/spine_rail.py."""
    r = run(["diff", "-rq", str(arms["control"] / "scripts"),
             str(arms["treatment"] / "scripts")])
    return r.stdout or ""


def build_settings(arms: dict) -> dict:
    """One settings file per arm. The hooks are wired BY ABSOLUTE PATH into that
    arm's own tree, `spine_rail.py` AHEAD of `gauge_writer_hook.py`.

    Everything except the two absolute paths is generated identically for both
    arms from this one function -- that is the whole experimental control.
    """
    out = {}
    sdir = TMP / "settings"
    sdir.mkdir(parents=True, exist_ok=True)
    for name, root in arms.items():
        hooks_dir = root / "scripts" / "hooks"
        settings = {
            "env": {
                # Identical in both arms. Measured NOT to lift the Bash
                # truncation ceiling on 2.1.223 (evidence/probe.json) -- kept
                # only so the two settings files stay generated by one code
                # path. Inflation goes through Read, which is not capped here.
                "BASH_MAX_OUTPUT_LENGTH": str(FILLER_CHARS + 50_000),
            },
            "permissions": {"allow": ["Bash", "Read", "Write", "Edit", "Task", "Glob", "Grep"]},
            "hooks": {
                "PostToolUse": [
                    {"matcher": "Bash", "hooks": [{
                        "type": "command",
                        "command": 'py "{0}" PostToolUse'.format(
                            (hooks_dir / "spine_rail.py").as_posix()),
                        "timeout": 15,
                    }]},
                    {"matcher": "*", "hooks": [{
                        "type": "command",
                        "command": 'py "{0}"'.format(
                            (hooks_dir / "gauge_writer_hook.py").as_posix()),
                        "timeout": 15,
                    }]},
                ]
            },
        }
        path = sdir / "{0}.json".format(name)
        path.write_text(json.dumps(settings, indent=2), encoding="utf-8")
        out[name] = path
    return out


